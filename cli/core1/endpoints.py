"""Contract files: .work/endpoints.json and .work/endpoints.env. Full contract in phase 8 (docs/contract.md)."""
import json

from .config import NETWORK, REGISTRY_CONTAINER, REGISTRY_INTERNAL_PORT
from .shell import log


def endpoints(settings):
    d = {
        "CORE1_ROOT": str(settings.root),
        "CORE1_DOCKER_NETWORK": NETWORK,
        "CORE1_REGISTRY_HOST_URL": settings.registry_host_url,
        "CORE1_REGISTRY_PUSH": f"127.0.0.1:{settings.registry_port}",
        "CORE1_REGISTRY_CLUSTER": settings.registry_use,
        "CORE1_REGISTRY_INTERNAL_URL": f"http://{REGISTRY_CONTAINER}:{REGISTRY_INTERNAL_PORT}",
    }
    for c in settings.clusters:
        key = f"CORE1_{c.name.upper()}"
        d[f"{key}_KUBECONFIG"] = str(c.kubeconfig(settings))
        d[f"{key}_API_URL"] = f"https://127.0.0.1:{c.api_port}"
        d[f"{key}_HTTP_URL"] = f"http://127.0.0.1:{c.http_port}"
        d[f"{key}_HTTPS_URL"] = f"https://127.0.0.1:{c.https_port}"
    return d


def write_endpoints(settings):
    settings.work_dir.mkdir(parents=True, exist_ok=True)
    d = endpoints(settings)
    env_path = settings.work_dir / "endpoints.env"
    json_path = settings.work_dir / "endpoints.json"
    env_path.write_text("# Core1 endpoints (host side). Generated by ./core1 endpoints; do not edit.\n"
                        + "".join(f"{k}={v}\n" for k, v in d.items()))
    json_path.write_text(json.dumps(d, indent=2) + "\n")
    for p in (env_path, json_path):
        p.chmod(0o600)
    log(f"endpoints written: {env_path.relative_to(settings.root)}, {json_path.relative_to(settings.root)}")
    return d
